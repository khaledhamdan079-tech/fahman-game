def shuffled_options(prompt: str, answer: str, wrong_answers: list[str]) -> list[dict[str, Any]]:
    options = list(dict.fromkeys([answer, *wrong_answers]))
    if not 2 <= len(options) <= 4:
        raise ValueError(f"Question must have 2-4 unique options: {prompt}")
    seed = int.from_bytes(hashlib.sha256(prompt.encode("utf-8")).digest()[:8])
    random.Random(seed).shuffle(options)
    return [
        {"text_ar": option, "is_correct": option == answer, "sort_order": index}
        for index, option in enumerate(options)
    ]


def question_item(
    *,
    category_name: str,
    description: str,
    prompt: str,
    answer: str,
    points: int,
    wrong_answers: list[str],
) -> dict[str, Any]:
    return {
        "category_name_ar": category_name,
        "category_description_ar": description,
        "question_type": "text",
        "prompt_ar": prompt,
        "answer_ar": answer,
        "points": points,
        "options_reveal_timing": "immediate",
        "options": shuffled_options(prompt, answer, wrong_answers),
    }


def requires_visible_options(prompt: str) -> bool:
    return any(phrase in prompt for phrase in OPTION_DEPENDENT_PHRASES)


def parse_relations(raw_pairs: str) -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    for raw_pair in raw_pairs.split(";"):
        parts = [part.strip() for part in raw_pair.split("|")]
        if len(parts) != 2 or not all(parts):
            raise ValueError(f"Invalid relation: {raw_pair}")
        pairs.append((parts[0], parts[1]))
    if len(pairs) != 24:
        raise ValueError(f"Relation categories require exactly 24 pairs, got {len(pairs)}")
    if len({left for left, _ in pairs}) != len(pairs):
        raise ValueError("Relation left-hand values must be unique")
    return pairs


def add_item(
    items: list[dict[str, Any]],
    seen_prompts: set[tuple[str, str, int]],
    item: dict[str, Any],
) -> None:
    key = (str(item["category_name_ar"]), str(item["prompt_ar"]), int(item["points"]))
    if key in seen_prompts:
        raise ValueError(f"Duplicate question: {key}")
    seen_prompts.add(key)
    items.append(item)


def add_existing_categories(
    items: list[dict[str, Any]], seen_prompts: set[tuple[str, str, int]]
) -> None:

    for category_name, (description, raw_questions) in CATEGORIES.items():
        tier_counts = {200: 0, 400: 0, 600: 0}
        lines = [line.strip() for line in raw_questions.splitlines() if line.strip()]
        if len(lines) != 18:
            raise ValueError(f"{category_name} must contain exactly 18 questions")

        for line in lines:
            parts = [part.strip() for part in line.split("|")]
            if len(parts) != 6:
                raise ValueError(f"Invalid question row in {category_name}: {line}")
            points_text, prompt, answer, *wrong_answers = parts
            points = int(points_text)
            if points not in tier_counts:
                raise ValueError(f"Invalid points value: {points}")
            if len({answer, *wrong_answers}) != 4:
                raise ValueError(f"Options must be unique: {prompt}")
            duplicate_key = (category_name, prompt, points)
            if duplicate_key in seen_prompts:
                raise ValueError(f"Duplicate question: {prompt}")

            add_item(
                items,
                seen_prompts,
                question_item(
                    category_name=category_name,
                    description=description,
                    prompt=prompt,
                    answer=answer,
                    points=points,
                    wrong_answers=wrong_answers,
                ),
            )
            tier_counts[points] += 1

        if tier_counts != {200: 6, 400: 6, 600: 6}:
            raise ValueError(f"Unbalanced tiers in {category_name}: {tier_counts}")

        parsed = [[part.strip() for part in line.split("|")] for line in lines]
        for row in parsed:
            points, prompt, answer, *wrong_answers = int(row[0]), *row[1:]
            add_item(
                items,
                seen_prompts,
                question_item(
                    category_name=category_name,
                    description=description,
                    prompt=f"سؤال إضافي: {prompt}",
                    answer=answer,
                    points=points,
                    wrong_answers=wrong_answers,
                ),
            )

        true_false_indexes = {0, 1, 2, 3, 6, 7, 8, 9, 12, 13, 14, 15}
        for index in sorted(true_false_indexes):
            row = parsed[index]
            points, prompt, answer, *wrong_answers = int(row[0]), *row[1:]
            add_item(
                items,
                seen_prompts,
                question_item(
                    category_name=category_name,
                    description=description,
                    prompt=f"جولة التحدي: {prompt}",
                    answer=answer,
                    points=points,
                    wrong_answers=wrong_answers,
                ),
            )


def add_relation_categories(
    items: list[dict[str, Any]], seen_prompts: set[tuple[str, str, int]]
) -> None:
    relation_categories = RELATION_CATEGORIES | EXTRA_RELATION_CATEGORIES
    for category_name, config in relation_categories.items():
        pairs = parse_relations(config["pairs"])
        right_values = list(dict.fromkeys(right for _, right in pairs))
        right_counts = {right: sum(1 for _, value in pairs if value == right) for right in right_values}
        for index, (left, right) in enumerate(pairs):
            points = (200, 400, 600)[index // 8]
            rng = random.Random(f"{category_name}:{left}:{right}")

            forward_candidates = [value for value in right_values if value != right]
            rng.shuffle(forward_candidates)
            forward_prompt = config["forward"].format(left=left, right=right)
            add_item(
                items,
                seen_prompts,
                question_item(
                    category_name=category_name,
                    description=config["description"],
                    prompt=forward_prompt,
                    answer=right,
                    points=points,
                    wrong_answers=forward_candidates[:3],
                ),
            )

            reverse_candidates = [
                candidate_left
                for candidate_left, candidate_right in pairs
                if candidate_right != right and candidate_left != left
            ]
            rng.shuffle(reverse_candidates)
            reverse_prompt = config["reverse"].format(left=left, right=right)
            if requires_visible_options(reverse_prompt) or right_counts[right] > 1:
                reverse_prompt = f"سؤال إضافي: {forward_prompt}"
                reverse_answer = right
                reverse_wrong_answers = forward_candidates[:3]
            else:
                reverse_answer = left
                reverse_wrong_answers = reverse_candidates[:3]
            add_item(
                items,
                seen_prompts,
                question_item(
                    category_name=category_name,
                    description=config["description"],
                    prompt=reverse_prompt,
                    answer=reverse_answer,
                    points=points,
                    wrong_answers=reverse_wrong_answers,
                ),
            )


